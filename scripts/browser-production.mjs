import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const headers=await readFile('public/_headers','utf8');
const csp=headers.split('\n').find(l=>l.includes('Content-Security-Policy:')).split('Content-Security-Policy:')[1].trim();
await page.route('http://127.0.0.1:4173/',async route=>{const response=await route.fetch();await route.fulfill({response,headers:{...response.headers(),'content-security-policy':csp}});});
await page.goto('http://127.0.0.1:4173/');
await page.locator('.scene-enhanced').waitFor();
await page.locator('#education').evaluate(e=>window.scrollTo(0,e.getBoundingClientRect().top+window.scrollY-250));
await page.waitForFunction(()=>document.querySelector('.programme-scenes').dataset.activeChapter==='education');
await page.locator('#health').evaluate(e=>window.scrollTo(0,e.getBoundingClientRect().top+window.scrollY-window.innerHeight*.25));
await page.waitForFunction(()=>document.querySelector('.programme-scenes').dataset.activeChapter==='health');
await page.locator('.scene-layer.is-active .gallery-open').focus();
await page.keyboard.press('Enter');
await page.getByRole('dialog').waitFor();
await page.getByRole('dialog').locator('img').evaluate(img=>img.decode());
assert.equal(await page.getByRole('dialog').locator('img').evaluate(img=>getComputedStyle(img).objectFit),'contain');
await page.screenshot({path:'output/playwright/production-portrait-dialog.png'});
await page.keyboard.press('Escape');
await page.getByRole('button',{name:'Projects & Possibilities',exact:true}).click();
await page.getByRole('button',{name:'Explore the learning sandbox'}).click();
await page.getByLabel('Perspective',{exact:true}).waitFor();
const response=await page.request.get('http://127.0.0.1:4173/downloads/introduction.pdf');
assert.equal(response.status(),200);
assert.deepEqual(errors,[]);
const nojs=await browser.newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});
await nojs.goto('http://127.0.0.1:4173/');
assert.equal(await nojs.locator('.static-story article[id^=static-]').count(),8);
assert.equal(await nojs.locator('.static-gallery').count(),0);
assert.equal(await nojs.locator('.static-story article[id^=static-] figure').count(),10);
assert.equal(await nojs.locator('#static-home details').count(),12);
assert.equal(await nojs.locator('#static-explore details').count(),5);
assert.deepEqual(await nojs.getByRole('navigation',{name:'Main navigation'}).getByRole('link').allTextContents(),['Home','Projects & Possibilities','About']);

await nojs.screenshot({path:'output/playwright/production-nojs-mobile.png'});
assert.equal(await nojs.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
await browser.close();
console.log('Production smoke passed: published CSP, chapters, portrait dialog, sandbox, PDF and mobile no-JavaScript story.');
