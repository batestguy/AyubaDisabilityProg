import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.clock.install();
await page.clock.pauseAt(new Date(Date.now()+1000));
await page.goto('http://127.0.0.1:5173');
const carousel=page.getByRole('region',{name:'Contributions in pictures'});
const slide=()=>carousel.locator('figure').getAttribute('aria-label');
assert.equal(await carousel.getByRole('button',{name:'Pause motion',exact:true}).count(),0);
await carousel.locator('img').waitFor();
assert.equal(await slide(),'Photograph 1 of 3');
await page.clock.runFor(3999);assert.equal(await slide(),'Photograph 1 of 3');
await page.clock.runFor(1);assert.equal(await slide(),'Photograph 2 of 3');
await carousel.hover();await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 3 of 3');
await carousel.getByRole('button',{name:'Next photograph'}).focus();
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 1 of 3');
await page.keyboard.press('ArrowRight');assert.equal(await slide(),'Photograph 2 of 3');
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 3 of 3');
await carousel.getByRole('button',{name:'Previous photograph'}).click();assert.equal(await slide(),'Photograph 2 of 3');
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 3 of 3');
assert.match(await carousel.locator('figcaption').innerText(),/CBM/);
await carousel.getByRole('button',{name:'Show photograph 1'}).click();
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 2 of 3');
await page.emulateMedia({reducedMotion:'reduce'});
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 3 of 3');
await page.emulateMedia({reducedMotion:'no-preference'});
await page.getByRole('button',{name:'Reduce motion',exact:true}).click();
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 1 of 3');
await page.getByRole('button',{name:'Reduce motion',exact:true}).click();
await page.setViewportSize({width:390,height:844});
await carousel.getByRole('button',{name:'Show photograph 2'}).click();
const image=carousel.locator('img');
assert.equal(await image.evaluate(el=>getComputedStyle(el).objectFit),'contain');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
await page.screenshot({path:'output/playwright/showcase-mobile.png',fullPage:true});
await carousel.dispatchEvent('touchstart',{touches:[{identifier:1,clientX:300,clientY:100}]});
await carousel.dispatchEvent('touchend',{changedTouches:[{identifier:1,clientX:100,clientY:110}]});assert.equal(await slide(),'Photograph 3 of 3');
await page.clock.runFor(4000);assert.equal(await slide(),'Photograph 1 of 3');
await page.setViewportSize({width:1440,height:1000});await carousel.getByRole('button',{name:'Show photograph 1'}).click();
await page.screenshot({path:'output/playwright/showcase-desktop.png',fullPage:true});
const failed=await browser.newPage();await failed.route('**/photos/noa.webp',r=>r.abort());await failed.goto('http://127.0.0.1:5173');await failed.getByText('Photograph unavailable.').first().waitFor();assert.match(await failed.locator('.photo-carousel figcaption').innerText(),/Gufwan/);
await failed.getByRole('button',{name:'Next photograph'}).click();await failed.locator('.photo-carousel img').waitFor();
assert.equal(await failed.locator('.photo-carousel img').evaluate(el=>el.complete&&el.naturalWidth>0),true);
assert.deepEqual(errors,[]);await browser.close();console.log('Carousel checks passed: 4s timing, continuous hover/focus/manual/reduced-motion cycling, keyboard, indicators, swipe, mobile frames, image failures.');
